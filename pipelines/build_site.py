#!/usr/bin/env python3
"""Assemble the GitHub Pages site (docs/) from the generated results.

Collects figures (PNG + plotly HTML) and tables (CSV) for the canonical ensemble
(configs/default.yaml: ensemble) plus the 6-vs-7 comparison, copies them into docs/,
and writes a self-contained index.html with relative links. Commit docs/ and enable
GitHub Pages (Settings -> Pages -> main / docs).

Usage: python pipelines/build_site.py
"""
from __future__ import annotations

import shutil
from pathlib import Path

import pandas as pd

from _common import REPO, load_config

DOCS = REPO / "docs"
ASSETS = DOCS / "assets"


def _copy(src: Path, rel: str) -> str | None:
    if not Path(src).exists():
        return None
    dst = ASSETS / rel
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)
    return f"assets/{rel}"


def _img(path, caption=""):
    return (f'<figure><img src="{path}" loading="lazy">'
            f'<figcaption>{caption}</figcaption></figure>') if path else \
        f'<p class="missing">[missing: {caption}]</p>'


def _iframe(path, caption=""):
    return (f'<figure><iframe src="{path}"></iframe>'
            f'<figcaption>{caption}</figcaption></figure>') if path else ""


def _table(csv, n=15):
    if not Path(csv).exists():
        return f'<p class="missing">[missing table: {csv}]</p>'
    df = pd.read_csv(csv)
    return df.head(n).to_html(index=False, classes="tbl", border=0)


def main():
    cfg = load_config()
    spec = cfg.get("ensemble", "6model")
    ASSETS.mkdir(parents=True, exist_ok=True)
    A = REPO / "results" / spec / "anomaly"
    C = REPO / "results" / spec / "conformal"
    K = REPO / "results" / spec / "classification"

    fig = {
        "cm_light": _copy(K / "confusion_test_light.png", "cm_light.png"),
        "cm_dark": _copy(K / "confusion_test_dark.png", "cm_dark.png"),
        "roc": _copy(A / "roc_ensemble_light.png", "roc.png"),
        "pr": _copy(A / "pr_ensemble_light.png", "pr.png"),
        "auroc_bar": _copy(A / "auroc_bar_light.png", "auroc_bar.png"),
        "detmap": _copy(A / "detection_map.png", "detection_map.png"),
        "umap_png": _copy(A / "umap_light.png", "umap.png"),
        "umap_html": _copy(A / "umap.html", "umap.html"),
        "cov": _copy(C / "uq_coverage.pdf", "uq_coverage.pdf"),
        "strat": _copy(C / "ad_strat_coverage.pdf", "ad_strat_coverage.pdf"),
        "vap": _copy(C / "ad_vap_coverage_per_quintile.pdf", "ad_vap.pdf"),
        "compare": _copy(REPO / "results" / "compare.png", "compare.png"),
    }

    html = f"""<!doctype html><html lang=en><head><meta charset=utf-8>
<meta name=viewport content="width=device-width,initial-scale=1">
<title>ASTRAnet — results</title>
<style>
 body{{font-family:system-ui,sans-serif;max-width:1100px;margin:2rem auto;padding:0 1rem;color:#1a1a1a;line-height:1.5}}
 h1{{color:#9f1239}} h2{{border-bottom:2px solid #f472b6;padding-bottom:.2rem;margin-top:2.5rem}}
 .grid{{display:grid;grid-template-columns:repeat(auto-fit,minmax(320px,1fr));gap:1rem}}
 figure{{margin:0;background:#fafafa;border:1px solid #eee;border-radius:8px;padding:.5rem}}
 img{{width:100%;height:auto;border-radius:4px}} iframe{{width:100%;height:420px;border:0}}
 figcaption{{font-size:.85rem;color:#555;text-align:center;margin-top:.3rem}}
 .tbl{{border-collapse:collapse;font-size:.8rem}} .tbl td,.tbl th{{border:1px solid #eee;padding:3px 7px}}
 .missing{{color:#aaa;font-style:italic}} code{{background:#f3f3f3;padding:1px 4px;border-radius:3px}}
 .note{{background:#fdf2f8;border-left:4px solid #e11d6a;padding:.6rem 1rem;border-radius:4px}}
</style></head><body>
<h1>ASTRAnet — results</h1>
<p class=note>Canonical ensemble: <b>{spec}</b> — the same model set is used for
every split, so classification, anomaly-detection and conformal numbers all come
from one consistent configuration.</p>
{_table(REPO/'results'/'compare.csv')}

<h2>Classification</h2>
<div class=grid>{_img(fig['cm_light'],'Test confusion matrix')}</div>

<h2>Anomaly detection (LUNA @ 1% FAR)</h2>
<div class=grid>
 {_img(fig['roc'],'ROC — ensemble anomaly score')}
 {_img(fig['pr'],'Precision–Recall')}
 {_img(fig['auroc_bar'],'Per-family AUROC')}
 {_img(fig['detmap'],'Detection map (per-anomaly × per-detector)')}
 {_img(fig['umap_png'],'UMAP — embeddings + rare overlay')}
</div>
{_iframe(fig['umap_html'],'Interactive UMAP')}
<h3>Top anomalies</h3>
{_table(A/'anomaly_report.csv')}

<h2>Conformal / UQ (§6)</h2>
<div class=grid>
 {_iframe(fig['strat'],'AD-stratified Mondrian coverage / quintile')}
 {_iframe(fig['cov'],'Coverage: empirical vs nominal')}
 {_iframe(fig['vap'],'AD-conditioned VAP coverage')}
</div>

<hr><p style="color:#888;font-size:.8rem">Generated by <code>pipelines/build_site.py</code>.
Models &amp; caches are git-ignored; regenerate with <code>bash run_all.sh</code>.</p>
</body></html>"""
    (DOCS / "index.html").write_text(html)
    print(f"Site written -> {DOCS}/index.html  (assets: {len(list(ASSETS.rglob('*')))} files)")


if __name__ == "__main__":
    main()
